#!/usr/bin/env python3
"""Writes tabs.h from the stock OS 1.54 main section (main.bin, from elekloader's syx.section(3), loaded at
0x40000400): each AMP knob value's attack length, hold length and the stock decay's time to -40 dB, in samples."""
import struct, math, sys
b = open(sys.argv[1] if len(sys.argv) > 1 else 'main.bin', 'rb').read()
def tab(a): o = a - 0x40000400; return struct.unpack('>128i', b[o:o + 512])
A = tab(0x4018f144); H = tab(0x4018ed44); D = tab(0x4018ef44)
att = [0] + [max(1, round(2**31 / -A[i])) for i in range(1, 128)]
dec = [0xFFFFFFFF if abs(D[i]) >= 2**31 else max(1, round(math.log(0.01) / math.log(abs(D[i]) / 2**31))) for i in range(128)]
def fmt(name, v):
    s = 'static const uint32_t %s[128] = {\n' % name
    for i in range(0, 128, 8):
        s += '    ' + ', '.join('%du' % x for x in v[i:i + 8]) + ',\n'
    return s + '};\n'
open('tabs.h', 'w').write('/* Generated by mk_tabs.py from the OS 1.54 tables (0x4018f144 attack steps, 0x4018ed44 hold,\n'
    ' * 0x4018ef44 decay coefficients). Samples at 48 kHz. */\n' + fmt('att_len', att) + fmt('hold_len', list(H)) +
    '/* the stock decay\'s time to -40 dB; 127 (coefficient -1) never decays: 0xffffffff */\n' + fmt('dec_len', dec) +
    '/* the stock decay coefficients, |c| in Q31 (for the stock curve with a synced hold) */\n' +
    fmt('dec_coef', [min(0x7fffffff, abs(x)) for x in D]))
